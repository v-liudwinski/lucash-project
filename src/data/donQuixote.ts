function ep(
  part: number,
  journey: number,
  chapter: number,
  place: string,
  kind: EpisodeKind,
  title: string,
  characters: string[],
  summary: string,
  highlights?: string[],
): Episode {
  return {
    id: `p${part}-${String(chapter).padStart(2, '0')}`,
    part,
    journey,
    chapters: String(chapter),
    title,
    kind,
    place,
    summary,
    highlights,
    characters,
  }
}

